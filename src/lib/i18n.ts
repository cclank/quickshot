function detectLanguage(): "zh" | "en" {
	const reported = typeof window !== "undefined" ? window.electronAPI?.language : undefined;
	if (reported === "zh" || reported === "en") return reported;
	const preferred =
		typeof navigator !== "undefined" ? [...(navigator.languages ?? []), navigator.language] : [];
	return preferred.some((item) => item?.toLowerCase().startsWith("zh")) ? "zh" : "en";
}

const language = detectLanguage();

const messages: Record<MessageKey, string> = language === "en" ? en : zh;

export const LANGUAGE = language;

export function t(key: MessageKey, values?: Record<string, string | number>) {
	const template = messages[key] ?? zh[key];
	if (!values) return template;
	return template.replace(/\{(\w+)\}/g, (match, name: string) =>
		name in values ? String(values[name]) : match,
	);
}
